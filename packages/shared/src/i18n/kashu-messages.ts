const MESSAGES: Record<KashuLocaleCode, MessageTable> = {
  en,
  es,
  fr,
  de,
  pt,
  ar,
  ja,
  zh,
  hi,
  it,
};

export function kashuT(
  locale: string,
  key: KashuMessageKey,
  vars?: Record<string, string | number>
): string {
  const loc = (normalizeKashuLocale(locale) as KashuLocaleCode) in MESSAGES ? normalizeKashuLocale(locale) as KashuLocaleCode : "en";
  let text = MESSAGES[loc][key] ?? MESSAGES.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return text;
}

function normalizeKashuLocale(raw: string): KashuLocaleCode {
  const base = raw.trim().split("-")[0]!.toLowerCase();
  if (base in MESSAGES) return base as KashuLocaleCode;
  return "en";
}

